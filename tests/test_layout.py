"""Red tests for the subtitle layout stubs.

Every test deliberately exercises a public function in
``subsrender.layout``; the initial checkout fails all fifteen because the
functions raise ``NotImplementedError``.  Do not edit this file.
"""

import pytest

from subsrender.layout import (
    SubRenderError,
    apply_shadow,
    layout_block,
    measure_text,
    outline_box,
    render_batch,
    safe_area_fit,
    validate_style,
    wrap_lines,
)


def _style(**overrides):
    style = {
        "font_size": 20.0,
        "line_height": 30.0,
        "outline": 2.0,
        "align": "center",
    }
    style.update(overrides)
    return style


def test_measure_text_counts_cjk_as_full_width():
    """Defect 1: half-width CJK makes measured lines half as wide."""
    width, height = measure_text("中文", _style())
    assert width == pytest.approx(40.0, abs=0.5)
    assert height == pytest.approx(30.0, abs=0.5)


def test_wrap_does_not_start_a_line_with_punctuation():
    """Defect 2: a closing punctuation mark must not form an orphan line."""
    lines = wrap_lines("你好，世界", _style(), 40.0)
    assert lines == ["你好，", "世界"]


def test_line_height_controls_vertical_step():
    """Defect 3: using font size as line height collapses line spacing."""
    result = layout_block(["第一行", "第二行"], _style(), (200.0, 100.0), "bottom-center")
    boxes = result["line_boxes"]
    assert len(boxes) == 2
    assert boxes[1]["y"] - boxes[0]["y"] == pytest.approx(30.0, abs=0.5)
    assert result["origin"][1] == pytest.approx(40.0, abs=0.5)


def test_all_nine_anchors_position_the_whole_block():
    """Defect 4: only bottom-center may not be hard-coded."""
    canvas = (200.0, 100.0)
    style = _style(align="left")
    expected = {
        "top-left": (0.0, 0.0),
        "top-center": (90.0, 0.0),
        "top-right": (180.0, 0.0),
        "center-left": (0.0, 35.0),
        "center": (90.0, 35.0),
        "center-right": (180.0, 35.0),
        "bottom-left": (0.0, 70.0),
        "bottom-center": (90.0, 70.0),
        "bottom-right": (180.0, 70.0),
    }
    for anchor, point in expected.items():
        result = layout_block(["AB"], style, canvas, anchor)
        assert result["origin"][0] == pytest.approx(point[0], abs=0.5), anchor
        assert result["origin"][1] == pytest.approx(point[1], abs=0.5), anchor


def test_outline_expands_outer_but_keeps_inner():
    """Defect 5: growing the inner frame crops glyphs."""
    box = {"x": 10.0, "y": 20.0, "w": 100.0, "h": 40.0}
    original = dict(box)
    result = outline_box(box, 3.0)
    assert result["inner"] == original
    assert result["outer"]["x"] == pytest.approx(7.0, abs=0.5)
    assert result["outer"]["y"] == pytest.approx(17.0, abs=0.5)
    assert result["outer"]["w"] == pytest.approx(106.0, abs=0.5)
    assert result["outer"]["h"] == pytest.approx(46.0, abs=0.5)
    assert box == original


def test_safe_area_moves_only_in_the_overflow_direction():
    """Defect 6: pushing from the wrong side covers neighbouring boxes."""
    result = safe_area_fit(
        {"x": 150.0, "y": 60.0, "w": 60.0, "h": 40.0},
        (200.0, 100.0),
        10.0,
    )
    assert result["x"] == pytest.approx(130.0, abs=0.5)
    assert result["y"] == pytest.approx(50.0, abs=0.5)
    assert result["w"] == pytest.approx(60.0, abs=0.5)
    assert result["h"] == pytest.approx(40.0, abs=0.5)

    left_top = safe_area_fit(
        {"x": -5.0, "y": 5.0, "w": 50.0, "h": 20.0},
        (200.0, 100.0),
        10.0,
    )
    assert left_top["x"] == pytest.approx(10.0, abs=0.5)
    assert left_top["y"] == pytest.approx(10.0, abs=0.5)


def test_shadow_is_clipped_to_canvas():
    """Defect 7: negative shadow coordinates escape the canvas."""
    box = {"x": 5.0, "y": 5.0, "w": 20.0, "h": 10.0, "canvas": (100.0, 50.0)}
    shadow = apply_shadow(box, (-10.0, -10.0), 4.0)
    assert shadow["x"] == pytest.approx(0.0, abs=0.5)
    assert shadow["y"] == pytest.approx(0.0, abs=0.5)
    assert shadow["w"] == pytest.approx(19.0, abs=0.5)
    assert shadow["h"] == pytest.approx(9.0, abs=0.5)


def test_validate_style_flags_line_height_smaller_than_font_size():
    """Defect 8: line height must be at least the font size."""
    issues = validate_style(_style(line_height=18.0))
    assert len(issues) == 1
    assert "line_height" in issues[0]


def test_batch_blocks_do_not_share_layout_buffers():
    """Defect 9: a shared buffer leaks line boxes into later blocks."""
    canvas = (200.0, 100.0)
    style = _style()
    blocks = [
        {"lines": ["第一行", "第二行"], "anchor": "top-left"},
        {"lines": ["第三行"], "anchor": "center"},
    ]
    batch = render_batch(blocks, canvas, style)
    first, second = batch["items"]
    assert len(first["line_boxes"]) == 2
    assert len(second["line_boxes"]) == 1
    solo = layout_block(["第三行"], style, canvas, "center")
    assert second["origin"][0] == pytest.approx(solo["origin"][0], abs=0.5)
    assert second["origin"][1] == pytest.approx(solo["origin"][1], abs=0.5)

    with pytest.raises(SubRenderError):
        render_batch(
            blocks + [{"lines": ["非法"], "anchor": "middle"}],
            canvas,
            style,
        )


def test_unknown_align_is_reported_and_rejected():
    """Defect 10: unknown alignment must not be silently centred."""
    style = _style(align="middle")
    issues = validate_style(style)
    assert any("align" in issue for issue in issues)
    with pytest.raises(SubRenderError):
        layout_block(["AB"], style, (100.0, 100.0), "center")


def test_single_character_uses_half_width_ratio():
    """Combination: one half-width glyph is font_size * 0.5 wide."""
    width, _height = measure_text("A", _style(font_size=18.0))
    assert width == pytest.approx(18.0 * 0.5, abs=0.5)


def test_wrap_still_makes_progress_when_max_width_is_tiny():
    """Combination: max_width below one glyph still yields usable lines."""
    assert wrap_lines("AB", _style(), 1.0) == ["A", "B"]


def test_zero_font_size_raises_sub_render_error():
    """Combination: invalid style is surfaced, not laid out."""
    with pytest.raises(SubRenderError):
        layout_block(["A"], _style(font_size=0.0), (100.0, 100.0), "center")


def test_empty_text_returns_no_lines():
    """Combination: empty subtitle has no line boxes to draw."""
    assert wrap_lines("", _style(), 100.0) == []


def test_batch_success_preserves_input_order():
    """Combination: all-valid batches keep the caller's order."""
    blocks = [
        {"lines": ["甲"], "anchor": "top-left"},
        {"lines": ["乙"], "anchor": "center"},
        {"lines": ["丙"], "anchor": "bottom-right"},
    ]
    result = render_batch(blocks, (200.0, 100.0), _style())
    assert result["count"] == 3
    items = result["items"]
    assert [item["anchor"] for item in items] == [
        "top-left",
        "center",
        "bottom-right",
    ]
    assert [item["line_boxes"][0]["text"] for item in items] == ["甲", "乙", "丙"]
